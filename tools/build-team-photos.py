"""Team portraits for /team.

    python tools/build-team-photos.py

The ten people in `assets/people/` are a matched set: one studio, one light,
one grey ground, black and white, every frame 4:5 and 600x750 (Yusra's is
1122x1402). Nothing is graded, cropped or retouched here - they already agree
with each other, and the page asks for exactly the 4:5 the drawn portraits
were authored at.

Output mirrors tools/build-client-marks.py, deliberately:

  - AVIF, WebP and JPEG at 240 and 480, with a content hash in every
    filename, so vercel.json's immutable year-long cache rule stays safe
  - `_manifest.json`, recording the source each plate came from
  - `site/assets/js/team-photos.js`, the srcsets as a record for team.js,
    the same shape and the same job as the generated clients.js

240 and 480 and no larger: the plate is about 230px wide in the 5-up grid at
1440 and about 165px in the 2-up on a phone, so 480 is already the 2x file.
Nothing is upscaled - every source is bigger than every plate written.

The names here are the join between the folder and the TEAM record in
site/assets/js/team.js. They are matched by hand, once, because the filenames
are people's names typed ten different ways and no rule reads them all.

Nothing here runs at request time. Run it when the photography changes, and
commit the output.
"""
import hashlib
import io
import json
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'people')
OUT = os.path.join(ROOT, 'site', 'assets', 'team')
REC = os.path.join(ROOT, 'site', 'assets', 'js', 'team-photos.js')

# slug -> the file in assets/people/. The slug is what team.js looks up.
PEOPLE = [
    ('abhinav-marothia', 'ABHINAV MAROTHIA.webp'),
    ('harshit-r',        'HARSHITH.webp'),
    ('sujeeth',          'SUJEETH.webp'),
    ('likhita-r-jain',   'LIKITHA R JAIN.webp'),
    ('manish-s',         'MANISH S.webp'),
    ('varun-ks',         'varun ks.webp'),
    ('yusra',            'yusra - client acquisition.webp'),
    ('manasi',           'Manasi doloi.webp'),
    ('hari-t',           'Hari T.webp'),
    ('manideep-chilukuri', 'Manideep.webp'),
]

WIDTHS = [240, 480]
RATIO = (4, 5)


def encode(im, fmt):
    buf = io.BytesIO()
    if fmt == 'avif':
        im.save(buf, 'AVIF', quality=58)
    elif fmt == 'webp':
        im.save(buf, 'WEBP', quality=80, method=6)
    else:
        im.save(buf, 'JPEG', quality=84, optimize=True, progressive=True)
    return buf.getvalue()


def main():
    os.makedirs(OUT, exist_ok=True)
    # a rebuild changes every hash, so clear the plates rather than leaving
    # the last run's orphans behind for the deploy to carry forever
    for f in os.listdir(OUT):
        if f.startswith('_'):
            continue
        os.remove(os.path.join(OUT, f))

    manifest, record = {}, {}
    for slug, fname in PEOPLE:
        path = os.path.join(SRC, fname)
        im = Image.open(path).convert('RGB')
        w, h = im.size
        # the set is already 4:5; assert rather than crop silently, so a
        # frame that is not gets looked at by a person
        assert abs(w / h - RATIO[0] / RATIO[1]) < 0.01, (fname, im.size)

        sets = {}
        for fmt in ('avif', 'webp', 'jpg'):
            parts = []
            for width in WIDTHS:
                assert width <= w, (fname, width, w)  # never upscale
                plate = im.resize((width, round(width * RATIO[1] / RATIO[0])), Image.LANCZOS)
                data = encode(plate, fmt)
                digest = hashlib.sha256(data).hexdigest()[:8]
                out = '%s-%d.%s.%s' % (slug, width, digest, fmt)
                with open(os.path.join(OUT, out), 'wb') as fh:
                    fh.write(data)
                parts.append('assets/team/%s %dw' % (out, width))
            sets[fmt] = ', '.join(parts)
        # the <img> needs one plain src too; the widest JPEG is the fallback
        sets['src'] = sets['jpg'].rsplit(', ', 1)[-1].rsplit(' ', 1)[0]
        record[slug] = sets
        manifest[slug] = {'source': fname, 'size': [w, h]}
        print('%-20s %s' % (slug, fname))

    with io.open(os.path.join(OUT, '_manifest.json'), 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
        fh.write('\n')

    head = (
        '/* ============================================================================\n'
        '   NUANSE — team-photos.js · the ten plates\n'
        '\n'
        '   GENERATED by tools/build-team-photos.py from assets/people/.\n'
        '   Do not hand-edit: the next run overwrites it. Replace the photograph.\n'
        '\n'
        '   Keyed by the slug on each record in team.js. The drawn portrait is still\n'
        '   built there and still carries the page on its own: if a slug here has no\n'
        '   plate, that person keeps the drawing and nothing else changes.\n'
        '   ========================================================================== */\n'
        'window.NU_TEAM_PHOTOS = '
    )
    with io.open(REC, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(head + json.dumps(record, indent=2, ensure_ascii=False) + ';\n')
    print('\n%d plates · %s' % (len(PEOPLE) * len(WIDTHS) * 3, OUT))


if __name__ == '__main__':
    main()
